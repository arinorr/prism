package diff

import (
	"strings"
	"testing"
)

const sampleDiff = `diff --git a/main.go b/main.go
index abc1234..def5678 100644
--- a/main.go
+++ b/main.go
@@ -10,6 +10,8 @@ func main() {
 	fmt.Println("hello")
 	fmt.Println("context1")
 	fmt.Println("context2")
+	fmt.Println("added line")
 	fmt.Println("context3")
 	fmt.Println("context4")
 	fmt.Println("context5")
`

const lockFileDiff = `diff --git a/package-lock.json b/package-lock.json
index 1234567..abcdefg 100644
--- a/package-lock.json
+++ b/package-lock.json
@@ -1,5 +1,5 @@
 {
-  "version": "1.0.0",
+  "version": "1.0.1",
   "dependencies": {
     "lodash": "4.17.21"
   }
`

const binaryDiff = `diff --git a/image.png b/image.png
Binary files a/image.png and b/image.png differ
`

const generatedDiff = `diff --git a/proto/service.pb.go b/proto/service.pb.go
index 111..222 100644
--- a/proto/service.pb.go
+++ b/proto/service.pb.go
@@ -1,3 +1,4 @@
 // Code generated by protoc-gen-go. DO NOT EDIT.
+// Added generated line
 package proto
`

const vendorDiff = `diff --git a/vendor/lib/util.go b/vendor/lib/util.go
index aaa..bbb 100644
--- a/vendor/lib/util.go
+++ b/vendor/lib/util.go
@@ -1,3 +1,4 @@
 package lib
+func Added() {}
`

func TestCompress_StripLockFiles(t *testing.T) {
	t.Parallel()
	input := sampleDiff + lockFileDiff
	result, summary := Compress(input, DefaultOptions())

	if strings.Contains(result, "package-lock.json") {
		t.Error("lock file should be stripped")
	}
	if !strings.Contains(result, "main.go") {
		t.Error("code file should be preserved")
	}
	if len(summary.FilesRemoved) != 1 || summary.FilesRemoved[0] != "package-lock.json" {
		t.Errorf("expected 1 removed file, got %v", summary.FilesRemoved)
	}
}

